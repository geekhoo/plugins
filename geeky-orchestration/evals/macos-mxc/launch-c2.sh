#!/bin/bash
# launch-c2.sh: C2 c2-linkvault, Claude Code harness in MXC (Seatbelt) on macOS, any LiteLLM model, with native
# OTel + post-run transcript upload + session scores in Langfuse (GEEKY_EVAL_SCORES=1). Non-reference on a Mac
# whose only allowed Python is Xcode 3.9.6 (C2 asks for 3.11+). Setup: README.md in this folder.
#
#   bash launch-c2.sh prepare <model> <effort>            # materialize only (no oracle, MXC or model calls)
#   bash launch-c2.sh run <model> <effort> <AUTH_REF>     # paid run: 10800 s budget, 900 s reserve, zero recovery
#   BRIDGE=1 bash launch-c2.sh run <gpt-model> ...        # route a non-Claude model through mxc-sandbox/bridge
#
# Paths (environment, with defaults):
#   MXC_EVAL_ROOT  eval root outside the repo: langfuse.env, tools/, pwsh-tool/, mxc-home/, work/, bridge-logs/
#   MXC_EVAL_REPO  this repository checkout (default: the checkout this script is in)
#   NODE_BIN       absolute node path; hooks inside the sandbox cannot rely on PATH (default: command -v node)
# The gateway comes from the operator's environment: ANTHROPIC_BASE_URL and ANTHROPIC_AUTH_TOKEN.
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=${MXC_EVAL_ROOT:-$HOME/mxc-eval}
REPO=${MXC_EVAL_REPO:-$(git -C "$HERE" rev-parse --show-toplevel)}
NODE_BIN=${NODE_BIN:-$(command -v node)}
mode=${1:-}; model=${2:-}; effort=${3:-}; auth=${4:-}
[ -n "$model" ] && [ -n "$effort" ] || { echo "usage: launch-c2.sh prepare|run <model> <effort> [AUTH_REF]" >&2; exit 2; }
[ -f "$ROOT/langfuse.env" ] || { echo "missing $ROOT/langfuse.env (copy langfuse.env.example, chmod 600)" >&2; exit 2; }
[ -n "${ANTHROPIC_BASE_URL:-}" ] && [ -n "${ANTHROPIC_AUTH_TOKEN:-}" ] || { echo "ANTHROPIC_BASE_URL / ANTHROPIC_AUTH_TOKEN not set" >&2; exit 2; }

set -a; . "$ROOT/langfuse.env"; set +a          # Langfuse keys + OTel content/delivery flags (private)
# Langfuse environment = the harness estate (Claude Code in MXC on macOS), on every channel: native OTel spans
# (resource attribute), transcript upload and automatic scores (LANGFUSE_TRACING_ENVIRONMENT).
LF_ENV=${LF_ENV:-mxc-claude-mac}
export LANGFUSE_TRACING_ENVIRONMENT="$LF_ENV"
export OTEL_RESOURCE_ATTRIBUTES="$(printf '%s' "${OTEL_RESOURCE_ATTRIBUTES:-}" | tr ',' '\n' | grep -v '^deployment\.environment\.name=' | grep -v '^$' | tr '\n' ',')deployment.environment.name=$LF_ENV"
# Full content for output evaluation: the transcript upload caps each string at CC_LANGFUSE_MAX_CHARS (default 20000).
export CC_LANGFUSE_MAX_CHARS=1000000 CLAUDE_CODE_OTEL_CONTENT_MAX_LENGTH=1000000
# agent-py first: the runner's pytest-interpreter probe then stops at the allowed Xcode 3.9 venv and never tries a
# blocked interpreter elsewhere on PATH. bin/ holds the pwsh shim (PowerShell on the allowed dotnet host).
export PATH="$ROOT/tools/agent-py/bin:$HERE/bin:/usr/local/share/dotnet:$PATH"
export MXC_EVAL_ROOT="$ROOT" MXC_SANDBOX_HOME="$ROOT/mxc-home"
export GEEKY_EVAL_MCP_RUNTIME=node
export GEEKY_EVAL_OTEL=1
export GEEKY_EVAL_EXTRA_RO="/Applications/Xcode.app/Contents:$ROOT/pwsh-tool:/usr/local/share/dotnet"
export LITELLM_PROXY_URL="$ANTHROPIC_BASE_URL" LITELLM_PROXY_API_KEY="$ANTHROPIC_AUTH_TOKEN"

# Non-Claude model compat layer (harness-side only; prompt and plugin export unchanged). Installed into the
# sandbox's isolated CLAUDE_CONFIG_DIR ($MXC_SANDBOX_HOME/home) for non-claude-* models, removed for Claude models:
#  - settings.json PreToolUse hook (evals/adapters/claude-code-litellm-compat/compat-hook.mjs);
#  - skills/geeky-orchestrator/SKILL.md generated by make-shim.mjs from the plugin's agents/geeky-orchestrator.md.
# Every intervention is logged to $MXC_SANDBOX_HOME/home/geeky-gpt-compat.log.jsonl.
CFGDIR="$MXC_SANDBOX_HOME/home"; COMPAT="$REPO/geeky-orchestration/evals/adapters/claude-code-litellm-compat"
compat_off() { rm -f "$CFGDIR/settings.json" "$CFGDIR/hooks/compat-hook.mjs"; rm -rf "$CFGDIR/skills/geeky-orchestrator"; }
if [[ "$model" =~ ^claude- ]]; then compat_off; echo "compat layer: off ($model)"
else
  compat_off; mkdir -p "$CFGDIR/hooks" "$CFGDIR/skills"
  cp "$COMPAT/compat-hook.mjs" "$CFGDIR/hooks/"
  "$NODE_BIN" "$COMPAT/make-shim.mjs" --agent "$REPO/geeky-orchestration/agents/geeky-orchestrator.md" --out "$CFGDIR/skills" >/dev/null
  printf '{\n  "hooks": {\n    "PreToolUse": [\n      { "matcher": "Skill|Agent|ToolSearch|SendMessage",\n        "hooks": [ { "type": "command", "command": "%s \\"$CLAUDE_CONFIG_DIR/hooks/compat-hook.mjs\\"", "timeout": 15 } ] }\n    ]\n  }\n}\n' "$NODE_BIN" > "$CFGDIR/settings.json"
  mv -f "$CFGDIR/geeky-gpt-compat.log.jsonl" "$CFGDIR/geeky-gpt-compat.log.prev.jsonl" 2>/dev/null || true
  echo "compat layer: on ($model) hook=$(shasum -a 256 "$CFGDIR/hooks/compat-hook.mjs" | cut -c1-12) shim=$(shasum -a 256 "$CFGDIR/skills/geeky-orchestrator/SKILL.md" | cut -c1-12)"
fi

args=(-Case c2-linkvault -Model "$model" -Effort "$effort" -Litellm -TimeoutSec 10800 -CloseoutReserveSec 900 -ResumeOnRefusal 0
      -NoTelemetry -ToolsDir "$ROOT/tools" -WorkRoot "$ROOT/work")
cd "$REPO/geeky-orchestration"
case "$mode" in
  prepare) exec pwsh -NoProfile -File evals/scripts/run-baseline.ps1 "${args[@]}" -AuthorizationReference prepare-check -PrepareOnly ;;
  run)
    [ -n "$auth" ] || { echo "usage: launch-c2.sh run <model> <effort> <AUTH_REF>" >&2; exit 2; }
    # The runner exports HEAD and mxc.ps1 builds the working tree's host: nothing may be uncommitted.
    [ -z "$(git -C "$REPO" status --porcelain -- geeky-orchestration mxc-sandbox ':!geeky-orchestration/evals/baselines')" ] \
      || { echo "uncommitted plugin or host changes: the runner exports HEAD; commit or stash first" >&2; exit 2; }
    # The host must already be built from the committed source (a rebuild inside the run would spend its budget).
    hostdir="$REPO/mxc-sandbox/scripts/host/MxcClaude"
    want=$(for f in MxcClaude.csproj Program.cs; do shasum -a 256 "$hostdir/$f" | awk '{print toupper($1)}'; done | tr -d '\n')
    [ "$(cat "$MXC_SANDBOX_HOME/bin/.source-hash" 2>/dev/null)" = "$want" ] \
      || { echo "host not built from the committed source: run mxc.ps1 -Rebuild probe first" >&2; exit 2; }
    # BRIDGE=1 (non-claude models): route through mxc-sandbox/bridge (Messages -> Responses API) so GPT gets the
    # gateway's prompt cache, reasoning summaries and effort. The bridge runs on the host for this run only; the
    # sandbox reaches it through --host-loopback. Per-request log: $ROOT/bridge-logs/<AUTH_REF>.jsonl.
    bridge_pid=""
    if [ "${BRIDGE:-0}" = 1 ] && [[ ! "$model" =~ ^claude- ]]; then
      BPORT=${BRIDGE_PORT:-8788}; mkdir -p "$ROOT/bridge-logs"
      BRIDGE_UPSTREAM="$ANTHROPIC_BASE_URL" BRIDGE_PORT=$BPORT BRIDGE_LOG="$ROOT/bridge-logs/$auth.jsonl" \
        "$NODE_BIN" "$REPO/mxc-sandbox/bridge/bridge.mjs" > "$ROOT/bridge-logs/$auth.out" 2>&1 & bridge_pid=$!
      for _ in $(seq 1 40); do curl -s -m 1 "http://127.0.0.1:$BPORT/health" >/dev/null 2>&1 && break; sleep 0.25; done
      curl -s -m 2 "http://127.0.0.1:$BPORT/health" >/dev/null || { echo "bridge did not start (see $ROOT/bridge-logs/$auth.out)" >&2; kill $bridge_pid 2>/dev/null; exit 2; }
      export LITELLM_PROXY_URL="http://127.0.0.1:$BPORT"
      echo "bridge: on pid=$bridge_pid port=$BPORT bridge.mjs=$(shasum -a 256 "$REPO/mxc-sandbox/bridge/bridge.mjs" | cut -c1-12) log=bridge-logs/$auth.jsonl"
      trap 'kill $bridge_pid 2>/dev/null' EXIT
    else echo "bridge: off"; fi
    rc=0; pwsh -NoProfile -File evals/scripts/run-baseline.ps1 "${args[@]}" -AuthorizationReference "$auth" || rc=$?
    exit $rc ;;
  *) echo "usage: launch-c2.sh prepare|run <model> <effort> [AUTH_REF]" >&2; exit 2 ;;
esac
