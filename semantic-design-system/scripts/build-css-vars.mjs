#!/usr/bin/env node
import path from 'node:path';
import {
  walkFiles,
  readJsonLike,
  deepMerge,
  collectTokens,
  resolveAlias,
  tokenValueToCss,
  cssVarName,
  projectPath,
  writeFileAtomic,
  classifyResolutionError,
  RESOLUTION_FAILURE_KINDS,
  TOKEN_FILE_RE,
  isThemeFile,
  DEFAULT_TOKEN_DIR
} from './token-utils.mjs';

const USAGE = 'Usage: build-css-vars.mjs [token-dir] [output-css-file] [prefix] [--allow-partial]';

const argv = process.argv.slice(2);
const flags = argv.filter(a => a.startsWith('--'));
const positional = argv.filter(a => !a.startsWith('--'));
const allowPartial = flags.includes('--allow-partial');
const unknownFlags = flags.filter(f => f !== '--allow-partial');

const tokenDir = projectPath(positional[0] || DEFAULT_TOKEN_DIR);
const outputFile = projectPath(positional[1] || process.env.DEFAULT_CSS_OUTPUT_FILE || 'src/styles/tokens.css');
const prefix = positional[2] || process.env.DEFAULT_CSS_PREFIX || 'ds';

const HEADER = '/* Generated by semantic-design-system plugin. Do not edit manually. */';

// Only `semantic.*` and `component.*` tokens become CSS custom properties.
// Primitives stay an implementation detail and are inlined via alias resolution.
function isExposed(tokenPath) {
  return tokenPath.startsWith('semantic.') || tokenPath.startsWith('component.');
}

// Resolve every exposed token in `context` to a final CSS string. Nothing is
// skipped silently: a token either lands in `resolved`, or in `failures` with
// its path, failure class, and the exact resolver message. Non-exposed tokens
// (primitives, `$`-prefixed nodes) are counted in `skipped` -- they are meant to
// stay out of the CSS surface and are not a problem.
function resolveLayer(context, layer) {
  const resolved = new Map();
  const failures = [];
  let skipped = 0;

  for (const [tokenPath, token] of context) {
    if (!tokenPath || tokenPath.startsWith('$') || !isExposed(tokenPath)) {
      skipped++;
      continue;
    }

    let css;
    try {
      css = tokenValueToCss(resolveAlias(token.node.$value, context, [tokenPath]));
    } catch (error) {
      failures.push({
        layer,
        tokenPath,
        kind: classifyResolutionError(error),
        error: error.message
      });
      continue;
    }

    // A brace surviving resolution means the value never reduced to a CSS scalar
    // -- typically a composite (typography/gradient) shape the builder cannot
    // flatten. Emitting it would put raw JSON into the stylesheet.
    if (typeof css !== 'string' || css.includes('{') || css.includes('}')) {
      failures.push({
        layer,
        tokenPath,
        kind: RESOLUTION_FAILURE_KINDS.UNSUPPORTED_VALUE_SHAPE,
        error: `value does not reduce to a CSS scalar (produced ${JSON.stringify(css)}); $type "${token.type || 'unknown'}" is not supported by the CSS builder`
      });
      continue;
    }

    resolved.set(tokenPath, css);
  }

  return { resolved, failures, skipped };
}

function declarationsFrom(resolvedMap) {
  return [...resolvedMap.keys()]
    .sort((a, b) => a.localeCompare(b))
    .map(p => `  ${cssVarName(p, prefix)}: ${resolvedMap.get(p)};`);
}

function block(selector, declarations, indent = '') {
  if (!declarations.length) return [];
  const out = [`${indent}${selector} {`];
  for (const d of declarations) out.push(`${indent}${d}`);
  out.push(`${indent}}`);
  return out;
}

function themeName(file) {
  return path.basename(file).replace(/\.tokens(\.jsonc?)?$/, '');
}

function formatFailures(failures) {
  return failures
    .map(f => `  [${f.layer}] ${f.tokenPath}: ${f.kind}: ${f.error}`)
    .join('\n');
}

let failures = [];
let counts = { emitted: 0, skipped: 0, failed: 0 };

try {
  if (unknownFlags.length) {
    throw new Error(`Unknown option(s): ${unknownFlags.join(', ')}. ${USAGE}`);
  }

  const files = walkFiles(tokenDir, f => TOKEN_FILE_RE.test(f));
  const baseFiles = files.filter(f => !isThemeFile(f));
  const themeFiles = files.filter(isThemeFile);

  // --- Phase 1: resolve and validate every layer BEFORE any CSS is generated.

  // Base layer: everything that is not a theme override.
  let baseTree = {};
  for (const f of baseFiles) baseTree = deepMerge(baseTree, readJsonLike(f));
  const base = resolveLayer(collectTokens(baseTree).tokens, 'base');

  failures.push(...base.failures);
  const baseFailed = new Set(base.failures.map(f => f.tokenPath));

  // Each theme is validated independently against the base tree, so a theme that
  // breaks a token is attributed to that theme instead of vanishing in the merge.
  // Failures already present in the base are not re-reported per theme; only
  // regressions the theme itself introduces are.
  const themeLayers = [];
  for (const file of themeFiles) {
    const name = themeName(file);
    const layer = `theme:${name}`;
    const themeTree = readJsonLike(file);
    const merged = resolveLayer(collectTokens(deepMerge(baseTree, themeTree)).tokens, layer);
    const introduced = merged.failures.filter(f => !baseFailed.has(f.tokenPath));
    failures.push(...introduced);
    themeLayers.push({ name, layer, resolved: merged.resolved, failures: introduced, skipped: merged.skipped });
  }

  counts.failed = failures.length;
  counts.skipped = base.skipped;

  // Fail closed. `--allow-partial` is the only way to get the old lenient behavior.
  if (failures.length && !allowPartial) {
    const error = new Error(
      `${failures.length} exposed token(s) failed to resolve; no CSS was written. ` +
      `Re-run with --allow-partial to emit the resolvable subset anyway.\n${formatFailures(failures)}`
    );
    error.failures = failures;
    throw error;
  }

  // --- Phase 2: generate CSS. Every token below is known-resolvable.

  const out = [HEADER];

  const rootDecls = declarationsFrom(base.resolved);
  let variableCount = rootDecls.length;
  out.push(...block(':root', rootDecls));

  // A theme declares only the tokens whose *resolved* value differs from the
  // base -- so an override of a primitive or semantic also re-emits every
  // component/semantic token that aliases it (the inlined cascade cannot
  // propagate on its own). Themes named `light`/`dark` additionally honor the OS
  // `prefers-color-scheme` when no explicit data-theme attribute is set, while an
  // explicit `[data-theme]` wins.
  const themes = [];
  for (const { name, resolved } of themeLayers) {
    const changed = new Map();
    for (const [p, css] of resolved) {
      // In --allow-partial runs a token may resolve under a theme but not in the
      // base. Emitting it would create a variable with no :root fallback, so it
      // stays out.
      if (!base.resolved.has(p)) continue;
      if (base.resolved.get(p) !== css) changed.set(p, css);
    }
    const decls = declarationsFrom(changed);
    if (!decls.length) continue;
    variableCount += decls.length;
    themes.push({ name, decls });
  }

  for (const { name, decls } of themes) {
    out.push('');
    out.push(...block(`[data-theme="${name}"]`, decls));
    if (name === 'light' || name === 'dark') {
      out.push('');
      out.push(`@media (prefers-color-scheme: ${name}) {`);
      out.push(...block(':root:not([data-theme])', decls, '  '));
      out.push('}');
    }
  }

  out.push('');
  counts.emitted = variableCount;

  // --- Phase 3: only now does anything touch the filesystem, and it does so via
  // a temp file that is renamed into place after the content validates.
  const css = out.join('\n');
  writeFileAtomic(outputFile, css, text => {
    if (!text.startsWith(HEADER)) throw new Error(`Generated CSS is missing its header: ${outputFile}`);
    const braces = (text.match(/\{/g) || []).length - (text.match(/\}/g) || []).length;
    if (braces !== 0) throw new Error(`Generated CSS has unbalanced braces: ${outputFile}`);
  });

  console.log(JSON.stringify({
    ok: true,
    tokenDir,
    outputFile,
    prefix,
    variables: variableCount,
    themes: themes.map(t => t.name),
    emitted: counts.emitted,
    skipped: counts.skipped,
    failed: counts.failed,
    allowPartial,
    partial: allowPartial && counts.failed > 0,
    failures
  }, null, 2));
} catch (error) {
  console.error(JSON.stringify({
    ok: false,
    tokenDir,
    outputFile,
    prefix,
    error: error.message,
    emitted: 0,
    skipped: counts.skipped,
    failed: counts.failed,
    allowPartial,
    failures: error.failures || failures
  }, null, 2));
  process.exit(1);
}
